import random

class Персонаж:
    def __init__(self, имя, hp, сила):
        self.имя = имя
        self._hp = hp
        self.сила = сила

    def получить_hp(self):
        return self._hp

    def получить_урон(self, урон):
        self._hp -= урон
        if self._hp < 0:
            self._hp = 0

    def жив(self):
        return self._hp > 0

    def атаковать(self, цель):
        урон = self.сила
        цель.получить_урон(урон)
        print(f"{self.имя} бьёт {цель.имя} на {урон} урона. "
              f"У {цель.имя} осталось {цель.получить_hp()} HP")


class Орк(Персонаж):
    def __init__(self, имя):
        super().__init__(имя, hp=100, сила=14)

    def атаковать(self, цель):
        урон = self.сила + random.randint(-2, 4)
        цель.получить_урон(урон)
        print(f" {self.имя} (Орк) яростно рубит {цель.имя} на {урон}! "
              f"У {цель.имя} осталось {цель.получить_hp()} HP")

class Эльф(Персонаж):
    def __init__(self, имя):
        super().__init__(имя, hp=95, сила=13)

    def атаковать(self, цель):
        print(f" {self.имя} (Эльф) выпускает две стрелы!")
        for _ in range(2):
            цель.получить_урон(self.сила)
        print(f"Суммарный урон {self.сила * 2}. "
              f"У {цель.имя} осталось {цель.получить_hp()} HP")

